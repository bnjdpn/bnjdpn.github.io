const days = (names, rest, join, twelve) => {
  const span = (a, b) => `${a}${join}${b}`;
  const t = twelve
    ? [['8:00 PM', '12:00 PM'], ['9:00 PM', '3:00 PM'], ['8:00 PM', '12:00 PM'], ['6:00 PM', '2:00 PM'], ['8:00 PM', '7:00 PM']]
    : [['20:00', '12:00'], ['21:00', '15:00'], ['20:00', '12:00'], ['18:00', '14:00'], ['20:00', '19:00']];
  const plans = [
    ['16:8', span(t[0][0], t[0][1]), false],
    [rest, '', true],
    ['18:6', span(t[1][0], t[1][1]), false],
    ['16:8', span(t[2][0], t[2][1]), false],
    ['20:4', span(t[3][0], t[3][1]), false],
    [rest, '', true],
    ['OMAD', span(t[4][0], t[4][1]), false],
  ];
  return names.map((name, i) => [name, plans[i][0], plans[i][1], plans[i][2]]);
};

